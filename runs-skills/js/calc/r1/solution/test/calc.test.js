import { test } from 'node:test';
import { evaluateLine } from '../src/calc.js';

const cases = [
  ['1 + 2 * 3', '7'],
  ['-7 / 2', '-3'],
  ['(1 + 2', 'error'],
  ['9223372036854775807 + 1', 'error'],
  ['-7 % 3', '-1'],
  ['7 % -3', '1'],
  ['(-9223372036854775807 - 1) % -1', '0'],
  ['(-9223372036854775807 - 1) / -1', 'error'],
  ['-9223372036854775808', 'error'],
  ['-9223372036854775807 - 1', '-9223372036854775808'],
  ['--5', '5'],
  ['1 - -2', '3'],
  ['-(2 + 3)', '-5'],
  ['()', 'error'],
  ['1 2', 'error'],
  ['+1', 'error'],
  ['1 +', 'error'],
  ['2)', 'error'],
  ['10 - 4 - 3', '3'],
  ['100 / 10 / 5', '2'],
  ['3037000500 * 3037000500', 'error'],
  ['-3037000499 * 3037000499', '-9223372030926249001'],
  ['1 / 0', 'error'],
  ['5 % 0', 'error'],
  ['\t 42 \t', '42'],
  ['  ', null],
  ['', null],
  ['1\r', 'error'],
  ['(' .repeat(100000) + '1' + ')'.repeat(100000), '1'],
];

for (const [input, want] of cases) {
  test(JSON.stringify(input.slice(0, 40)), (t) => t.assert.equal(evaluateLine(input), want));
}
