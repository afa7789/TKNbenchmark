// ---------- formatting ----------
const nf = (d) => new Intl.NumberFormat('en-US', { maximumFractionDigits: d, minimumFractionDigits: d })
const isNum = (v) => typeof v === 'number' && Number.isFinite(v)
const guard = (f) => (v) => (isNum(v) ? f(v) : 'n/a')
const fmt = {
  usd: guard((v) => `$${nf(v < 1 ? 3 : 2).format(v)}`),
  int: guard((v) => nf(0).format(Math.round(v))),
  num1: guard((v) => nf(1).format(v)),
  pct: guard((v) => `${nf(0).format(v * 100)}%`),
  secs: guard((v) => (v >= 90 ? `${nf(1).format(v / 60)} min` : `${nf(v < 10 ? 1 : 0).format(v)} s`)),
  ms: guard((v) => (v >= 1000 ? `${nf(2).format(v / 1000)} s` : `${nf(0).format(v)} ms`)),
  bytes: guard((v) => (v >= 1e9 ? `${nf(2).format(v / 1e9)} GB` : v >= 1e6 ? `${nf(1).format(v / 1e6)} MB` : `${nf(0).format(v / 1e3)} KB`)),
  rps: guard((v) => `${nf(0).format(v)} req/s`),
  ratio: guard((v) => `×${nf(2).format(v)}`),
}

