function renderLeaderboard(d, sort = { key: 'costUsd', dir: 1 }) {
  const rows = Object.entries(d.summary.langs).sort((a, b) => sort.dir * ((a[1][sort.key] ?? Infinity) - (b[1][sort.key] ?? Infinity)))
  const head = `<tr><th>#</th><th>Language</th>${LB_COLS.map((c) => `<th class="num" data-sort="${c.key}" aria-sort="${sort.key === c.key ? (sort.dir > 0 ? 'ascending' : 'descending') : 'none'}">${esc(c.title)}</th>`).join('')}</tr>`
  const body = rows
    .map(([k, s], i) => `<tr><td>${i + 1}</td><td><strong>${esc(d.meta.langs[k].label)}</strong></td>${LB_COLS.map((c) => `<td class="num">${c.show(s)}</td>`).join('')}</tr>`)
    .join('')
  $('leaderboard').innerHTML = `<table><thead>${head}</thead><tbody>${body}</tbody></table>`
  $('leaderboard').querySelectorAll('th[data-sort]').forEach((th) =>
    th.addEventListener('click', () => {
      const key = th.dataset.sort
      const higher = ['passRate', 'works', 'firstTryRate'].includes(key)
      const dir = sort.key === key ? -sort.dir : higher ? -1 : 1
      renderLeaderboard(d, { key, dir })
    }),
  )
}

