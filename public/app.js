const fwLabel = (d, k) => d.meta.frontends[k].label
const totalKey = (t) => (t === 'opus' ? 'codeTokens' : 'codeTokensCl100k')

function fwRow(fws, title, get, cls = '') {
  const cells = (t) => fws.map((k) => `<td class="num">${fmt.int(get(k, t))}</td>`).join('')
  return `<tr class="${cls}"><td>${esc(title)}</td>${cells('opus')}${cells('cl100k')}</tr>`
}

function componentTable(d, F, fws) {
  const names = [...new Set(fws.flatMap((k) => Object.keys(F[k].components)))]
  const rows = names.map((n) => fwRow(fws, n, (k, t) => F[k].components[n]?.[t]?.median))
  rows.push(fwRow(fws, 'Total', (k, t) => F[k][totalKey(t)]?.median, 'highlight'))
  rows.push(`<tr><td>Works (build + browser)</td>${fws.map((k) => `<td class="num">${F[k].solved}/${F[k].n}${F[k].works > F[k].solved ? ` → ${F[k].works}/${F[k].n}` : ''}</td>`).join('')}${fws.map(() => '<td></td>').join('')}</tr>`)
  rows.push(`<tr><td>Agent cost per run</td>${fws.map((k) => `<td class="num">${fmt.usd(F[k].costUsd?.median)}</td>`).join('')}${fws.map(() => '<td></td>').join('')}</tr>`)
  const head = [{ title: 'Component' }, ...['Opus', 'cl100k'].flatMap((t) => fws.map((k) => ({ title: `${fwLabel(d, k)} (${t})`, num: true })))]
  return table(head, rows)
}

// Our totals as multiples of Svelte, next to the article's published multipliers.
function validationTable(d, F, fws) {
  const base = (t) => F.svelte?.[totalKey(t)]?.median
  if (!base('opus')) return ''
  const rows = fws.map((k) => {
    const article = d.meta.external.multipliers[fwLabel(d, k)]
    return `<tr><td>${esc(fwLabel(d, k))}</td><td class="num">${fmt.ratio(article)}</td><td class="num">${fmt.ratio(F[k].codeTokensCl100k.median / base('cl100k'))}</td><td class="num">${fmt.ratio(F[k].codeTokens.median / base('opus'))}</td></tr>`
  })
  return `<h3>Against the article (Svelte = ×1.00)</h3>${table([{ title: 'Framework' }, { title: 'Article (cl100k)', num: true }, { title: 'Ours (cl100k)', num: true }, { title: 'Ours (Opus 5.5)', num: true }], rows)}`
}

