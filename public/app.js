// Copy buttons next to the donation addresses.
function initCopy() {
  document.addEventListener('click', async (e) => {
    const btn = e.target.closest('[data-copy]')
    if (!btn) return
    await navigator.clipboard.writeText(btn.dataset.copy).catch(() => {})
    btn.textContent = 'Copied'
    setTimeout(() => (btn.textContent = 'Copy'), 1500)
  })
}

function initTooltip() {
  const tip = $('tip')
  const place = (e) => {
    tip.style.left = `${Math.min(e.clientX + 14, innerWidth - tip.offsetWidth - 8)}px`
    tip.style.top = `${e.clientY + 14}px`
  }
  document.addEventListener('mouseover', (e) => {
    const el = e.target.closest('[data-tip]')
    if (!el) return
    tip.textContent = el.dataset.tip
    tip.style.display = 'block'
    place(e)
  })
  document.addEventListener('mousemove', (e) => tip.style.display === 'block' && place(e))
  document.addEventListener('mouseout', (e) => e.target.closest('[data-tip]') && (tip.style.display = 'none'))
}

// ---------- building blocks ----------
function barChart({ title, sub, rows, format, higherIsBetter = false }) {
  const max = Math.max(...rows.map((r) => r.value).filter(isNum), 0) || 1
  const order = (a, b) => (isNum(a.value) ? (isNum(b.value) ? (higherIsBetter ? b.value - a.value : a.value - b.value) : -1) : 1)
  const body = [...rows]
    .sort(order)
    .map((r) => {
      const w = isNum(r.value) ? Math.max(0.5, (r.value / max) * 100) : 0
      return `<span class="name">${esc(r.label)}</span><span class="track${isNum(r.value) ? '' : ' na'}" data-tip="${esc(r.tip ?? `${r.label}: ${format(r.value)}`)}"><span class="bar" style="width:${w}%"></span><span class="val">${format(r.value)}</span></span>`
    })
    .join('')
  return `<div class="chart"><h4>${esc(title)}</h4>${sub ? `<p class="sub">${esc(sub)}</p>` : ''}<div class="bars">${body}</div></div>`
}

const ranged = (s, f) => (s ? `${f(s.median)}${s.n > 1 ? `<span class="range">${f(s.min)}–${f(s.max)}</span>` : ''}` : 'n/a')

function table(head, rows) {
  return `<table><thead><tr>${head.map((h) => `<th class="${h.num ? 'num' : ''}">${esc(h.title)}</th>`).join('')}</tr></thead><tbody>${rows.join('')}</tbody></table>`
}

// ---------- sections ----------
function bestBy(langs, key, pickMax = false) {
  const entries = Object.entries(langs).filter(([, s]) => isNum(s[key]))
  entries.sort((a, b) => (pickMax ? b[1][key] - a[1][key] : a[1][key] - b[1][key]))
  return entries[0]
}

function tile(d, title, key, f, note, pickMax = false) {
  const best = bestBy(d.summary.langs, key, pickMax)
  if (!best) return [title, 'n/a', note]
  const tied = Object.keys(d.summary.langs).filter((k) => d.summary.langs[k][key] === best[1][key])
  const who = tied.length > 1 ? `Tie (${tied.length})` : d.meta.langs[best[0]].label
  const names = tied.length > 1 ? `${tied.map((k) => d.meta.langs[k].label).join(', ')}: ` : ''
  return [title, who, `${names}${f(best[1][key])} · ${note}`]
}

