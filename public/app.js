function repairRow(d, r) {
  const status = r.fixed === null ? 'not repaired' : r.fixed ? `fixed in ${r.repairAttempts}` : `failed ${r.repairAttempts}×`
  const tip = r.repairLog.map((a) => `attempt ${a.n}: ${a.pass}/${a.total}, ${fmt.usd(a.costUsd)}, ${fmt.secs(a.durationS)}`).join('\n')
  return `<tr><td>${esc(label(d, r.lang))}</td><td>${esc(r.task)} r${r.rep}</td><td class="num">${r.pass}/${r.total}</td><td>${esc(r.failures[0]?.name ?? 'build')}</td><td class="num" data-tip="${esc(tip)}">${esc(status)}</td><td class="num">${fmt.usd(r.repairCostUsd)}</td><td class="num">${fmt.secs(r.repairDurationS)}</td><td class="num">${fmt.int(r.repairOutput)}</td><td class="num">${fmt.usd(r.costUsd)} → ${fmt.usd(r.costToGreenUsd)}</td></tr>`
}

function renderRepair(d) {
  const failed = d.runs.filter((r) => r.solved === false)
  const total = d.runs.filter((r) => r.solved !== null).length
  if (!failed.length) {
    $('repair-table').innerHTML = `<p><strong>None of the ${total} runs failed round 3.</strong> Nothing to repair.</p>`
    return
  }
  const fixed = failed.filter((r) => r.fixed).length
  const head = ['Language', 'Case', 'Round 3', 'First failure', 'Result', 'Repair cost', 'Time', 'Output tokens', 'Cost to green'].map((title, i) => ({ title, num: i >= 2 && i !== 3 }))
  $('repair-table').innerHTML = `<p><strong>${failed.length} of ${total}</strong> runs failed round 3; <strong>${fixed}</strong> were fixed.</p>${table(head, failed.map((r) => repairRow(d, r)))}`
}

