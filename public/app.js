const byKey = (langs, key, dir = 1) => Object.keys(langs).filter((k) => isNum(langs[k][key])).sort((a, b) => dir * (langs[a][key] - langs[b][key]))
const names = (d, ks) => ks.map((k) => label(d, k)).join(', ')
const li = (head, body) => `<li><strong>${esc(head)}</strong> ${body}</li>`

function baseFindings(d) {
  const L = d.summary.langs
  const cost = byKey(L, 'costUsd')
  const speed = byKey(L, 'perfScore')
  const [cheap, dear, fast] = [cost[0], cost.at(-1), speed[0]]
  const works = Object.values(L).reduce((s, x) => s + x.works, 0)
  const total = Object.values(L).reduce((s, x) => s + x.n, 0)
  return [
    li('The language changes the bill, not whether the code works.', `${esc(label(d, cheap))} was cheapest (${fmt.usd(L[cheap].costUsd)} for 4 tasks), ${esc(label(d, dear))} the most expensive (×${nf(1).format(L[dear].costUsd / L[cheap].costUsd)}); ${works}/${total} runs ended passing every hidden test.`),
    li('Cheap to write is not fast to run.', `Cost and code speed rank against each other (Spearman ρ = ${nf(2).format(d.summary.costSpeedRho)}): the cheapest to write (${esc(names(d, cost.slice(0, 3)))}) wrote code ${fmt.ratio(Math.min(...cost.slice(0, 3).map((k) => L[k].perfScore)))}–${fmt.ratio(Math.max(...cost.slice(0, 3).map((k) => L[k].perfScore)))} slower than the fastest, ${esc(label(d, fast))}.`),
  ]
}

const speedMedian = (rows) => {
  const xs = rows.filter((r) => r.main && isNum(r.speedChange)).map((r) => r.speedChange).sort((a, b) => a - b)
  return xs[xs.length >> 1]
}

function skillFindings(d, arm) {
  const rows = skillRows(arm)
  const e = arm.summary.effect
  const pctOf = (m) => signed(change(m.base, m.arm))
  const costlier = rows.filter((r) => r.dCost > 0 && r.beyondNoise).length
  const cheaper = rows.filter((r) => r.dCost < 0 && r.beyondNoise).length
  const zig = arm.summary.vsBase.zig
  const works = (side) => rows.reduce((s, r) => s + r[side].works, 0)
  const n = (side) => rows.reduce((s, r) => s + r[side].n, 0)
  const out = [
    li('A language skill made the agent costlier, not cheaper.', `With one researched SKILL.md per language, ${costlier} of ${rows.length} languages cost more beyond their run-to-run spread and ${cheaper} cost less; per run, the median went ${fmt.usd(e.costUsd.base)} → ${fmt.usd(e.costUsd.arm)} (${pctOf(e.costUsd)}). Correctness did not move (${works('arm')}/${n('arm')} runs worked with it, ${works('base')}/${n('base')} without), nor did the speed of the code (median ${fmt.ratio(speedMedian(rows))}, measured paired).`),
    li('The skill is paid as context, not as work.', `Loading and applying it takes ${nf(0).format(e.turns.arm - e.turns.base)} more turns per run (${e.turns.base} → ${e.turns.arm}); ${fmt.pct(e.costShare.cacheWrite)} of the extra spend is context written to the prompt cache (the skill's text and those turns, at twice the input price), ${fmt.pct(e.costShare.cacheRead)} context re-read and only ${fmt.pct(e.costShare.output)} the agent's own output.`),
  ]
  if (e.durationS) out.push(li('Nor did it save time.', `The median run took ${fmt.secs(e.durationS.base)} without the skill and ${fmt.secs(e.durationS.arm)} with it (${signed(change(e.durationS.base, e.durationS.arm))}); only ${e.fasterRuns} of ${e.pairs} runs finished sooner with it.`))
  const c = e.code
  if (c) {
    out.push(li('The code was not better, only more tested.', `With the skill, ${c.solved.arm} of ${e.pairs} runs passed the hidden tests in round 3 (${c.solved.base} without), the examples passed on the first check in ${c.firstTry.arm} (${c.firstTry.base}), and the code ran as fast (median ${fmt.ratio(speedMedian(rows))}) at about the same size (${fmt.int(c.codeTokens.base)} → ${fmt.int(c.codeTokens.arm)} tokens, median run). What changed was the process: ${c.withTests.arm} runs left tests behind (${c.withTests.base} without), in more files (${c.files.base} → ${c.files.arm}), and met more compiler errors on the way (${c.compileErrors.base} → ${c.compileErrors.arm}). The model already knows these languages; the hidden tests, not the skill, kept the code correct.`))
  }
  const len = arm.summary.length
  if (len) {
    const [short, long] = [len.bins[0], len.bins.at(-1)]
    out.push(li('The longer the task, the less the skill costs, but our tasks are short.', `Where the agent needed fewer than ${short.hi} turns without the skill, the skill added ${signed(short.median)}; where it needed ${long.lo} or more, ${signed(long.median)} (${long.n} cases; Spearman ρ = ${nf(2).format(len.rho)} between task length and the increase). The fixed price of loading it shrinks as the work grows, so a fair test of skills needs longer tasks than these.`))
  }
  if (zig) out.push(li('Where the model is out of date, a skill replaces work instead of adding it.', `Zig 0.16 changed its I/O API: with the skill the agent read the standard library's source ${nf(0).format(zig.base.stdlibReads)} → ${nf(0).format(zig.arm.stdlibReads)} times and wrote ${signed(change(zig.base.output, zig.arm.output))} output, for the same cost (${signed(change(zig.base.costUsd, zig.arm.costUsd))}${zig.beyondNoise ? '' : ', within noise'}).`))
  return out
}

function howTo(d, arm) {
  const L = d.summary.langs
  const tips = [
    `<li><strong>Cheapest for an agent to write:</strong> ${esc(names(d, byKey(L, 'costUsd').slice(0, 3)))}. <strong>Fastest code:</strong> ${esc(names(d, byKey(L, 'perfScore').slice(0, 3)))}. Pick by what you pay for more: agent time or CPU time.</li>`,
    '<li><strong>Check the I/O idiom before blaming the language.</strong> C++ was slow on <code>calc</code> because the agent read stdin through <code>istreambuf_iterator</code> one character at a time; the same code with <code>fread</code> ran ~20× faster (paper, Discussion).</li>',
  ]
  if (!arm) return tips
  const rows = skillRows(arm)
  const pays = rows.filter((r) => isNum(r.breakEvenRuns)).length
  tips.push(
    `<li><strong>Do not add a generic language skill by default.</strong> On tasks of a few turns it saved money, beyond run-to-run noise, in ${pays} of ${rows.length} languages. Measure it on your own tasks first, as in <a href="#skills">With a language skill</a>.</li>`,
    '<li><strong>Write a skill only for what the model gets wrong today</strong> (an API that changed after its training, a house convention), and keep it short: its text, and every turn it adds, is written into the context at twice the input price.</li>',
  )
  return tips
}

